"""Write docs/SCRIPTS.md from each script's docstring. Run after adding or changing a script; edit docstrings, never SCRIPTS.md.
--check: write nothing, exit 1 if SCRIPTS.md differs from what this would write (a unit test runs it). A new scripts/ folder needs a row in SEC."""
import ast, glob, os, sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEC = [("scripts", "Core tools, used by the stages", "scripts/*.py"), ("scripts/validate", "Validation and SV evidence", "scripts/validate/*.py"), ("scripts/rescue", "Hi-C allele rescue (settings.hic_allele_rescue)", "scripts/rescue/*.py"), ("scripts/review", "Review helpers for decisions", "scripts/review/*.py"), ("scripts/rawreads", "Raw reads and join tests", "scripts/rawreads/*.py"), ("scripts/ttt", "Optional TTT tangle test (docs/TANGLES.md)", "scripts/ttt/*.py"), ("scripts/cleanup", "Freeing disk after a run (docs/CLEANUP.md)", "scripts/cleanup/*.py")]
out = ["# Scripts\n", "Generated by `tools/gen_scripts_doc.py` from each script's docstring. Run a script with no arguments, or `-h`, for its usage.\n"]
for _, title, pat in SEC:
    out.append(f"## {title}\n"); out.append("| Script | Purpose |\n|---|---|")
    for f in sorted(glob.glob(os.path.join(R, pat))):
        d = ast.get_docstring(ast.parse(open(f).read())) or ""
        one = " ".join(d.split("Usage:")[0].split())
        one = one.replace('|', '/')
        if len(one) > 220: one = one[:220].rsplit(" ", 1)[0].rstrip(",;:") + " ..."   # cut at a word, not inside one
        out.append(f"| `{os.path.relpath(f, R)}` | {one or '(see source)'} |")
    out.append("")
text = "\n".join(out); P = os.path.join(R, "docs", "SCRIPTS.md")
if "--check" in sys.argv[1:]:
    if open(P).read() != text: sys.exit("docs/SCRIPTS.md is out of date: run tools/gen_scripts_doc.py")
else: open(P, "w").write(text)
missing = sorted({os.path.dirname(os.path.relpath(f, R)) for f in glob.glob(os.path.join(R, "scripts", "**", "*.py"), recursive=True)} - {d for d, _, _ in SEC})
if missing: sys.exit(f"scripts folders not in SEC, so missing from SCRIPTS.md: {missing}")
