"""Write docs/SCRIPTS.md from each script's docstring. Run after adding or changing a script."""
import ast, glob, os
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEC = [("scripts", "Core tools, used by the stages", "scripts/*.py"), ("scripts/validate", "Validation and SV evidence", "scripts/validate/*.py"), ("scripts/review", "Review helpers for decisions", "scripts/review/*.py"), ("scripts/rawreads", "Raw reads and join tests", "scripts/rawreads/*.py")]
out = ["# Scripts\n", "Generated by `tools/gen_scripts_doc.py` from each script's docstring. Run a script with no arguments, or `-h`, for its usage.\n"]
for _, title, pat in SEC:
    out.append(f"## {title}\n"); out.append("| Script | Purpose |\n|---|---|")
    for f in sorted(glob.glob(os.path.join(R, pat))):
        d = ast.get_docstring(ast.parse(open(f).read())) or ""
        one = " ".join(d.split("Usage:")[0].split())
        out.append(f"| `{os.path.relpath(f, R)}` | {one.replace('|', '/')[:220] + ('...' if len(one) > 220 else '') or '(see source)'} |")
    out.append("")
open(os.path.join(R, "docs", "SCRIPTS.md"), "w").write("\n".join(out))
